// Build time photo placeholders (2026-11-27). Astro integration (astro.config.mjs).
//
// For every photo in src/assets/images/projects it writes one CSS rule to
// src/styles/photo-placeholders.css: a vertical gradient of the photo's top, middle and bottom
// colors (sharp shrinks the photo to 1x3 pixels). PhotoSlot puts the class on the photo's
// <figure>, so a lazy photo shows a hint of itself, not a flat gray box, until it loads.
// Plain CSS in a file: no inline styles and no data: URIs, so the Content-Security-Policy stays
// as is. No runtime network calls. The file is generated (git ignored) and only rebuilt when a
// photo is newer than it.
import { readdirSync, statSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import sharp from 'sharp';
import { placeholderClass } from '../src/lib/placeholder-class.mjs';

const PHOTO_DIR = 'src/assets/images/projects';
const OUT = 'src/styles/photo-placeholders.css';
const hex = (r, g, b) => '#' + [r, g, b].map((v) => v.toString(16).padStart(2, '0')).join('');

export async function generatePlaceholders(root = process.cwd()) {
  const dir = join(root, PHOTO_DIR);
  const out = join(root, OUT);
  const files = readdirSync(dir).filter((f) => /\.(jpe?g|png|webp)$/i.test(f)).sort();
  const newest = Math.max(...files.map((f) => statSync(join(dir, f)).mtimeMs));
  if (existsSync(out) && statSync(out).mtimeMs >= newest && statSync(out).mtimeMs >= statSync(new URL(import.meta.url)).mtimeMs) return { files: files.length, skipped: true };
  const rules = [];
  for (const f of files) {
    const { data } = await sharp(join(dir, f)).resize(1, 3, { fit: 'fill' }).removeAlpha().raw().toBuffer({ resolveWithObject: true });
    const stops = [0, 1, 2].map((i) => hex(data[i * 3], data[i * 3 + 1], data[i * 3 + 2]));
    rules.push(`.${placeholderClass(f.split('.')[0])}{background-image:linear-gradient(${stops.join(',')})}`);
  }
  writeFileSync(out, `/* Generated by scripts/placeholders.mjs at build time. Do not edit. */\n${rules.join('\n')}\n`);
  return { files: files.length, skipped: false };
}

export function photoPlaceholders() {
  return {
    name: 'ecm-photo-placeholders',
    hooks: {
      'astro:config:setup': async ({ logger }) => {
        const t = Date.now();
        const r = await generatePlaceholders();
        logger.info(`${r.skipped ? 'up to date' : 'generated'}: ${r.files} photos (${Date.now() - t}ms)`);
      },
    },
  };
}
